#!/usr/bin/env node
// Generates both browser PGlite SQL bundles from the ordered Drizzle migrations.
// Fresh databases replay the exact migration chain. Existing IndexedDB databases
// replay an idempotent compatibility bundle; migration 0001 needs a one-time
// backfill because legacy app_user rows predate password_hash.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DRIZZLE_DIR = path.join(ROOT, 'drizzle');
const JOURNAL_PATH = path.join(DRIZZLE_DIR, 'meta', '_journal.json');
const SCHEMA_PATH = path.join(ROOT, 'web/public/db/erp-system-schema.sql');
const MIGRATIONS_PATH = path.join(ROOT, 'web/public/db/erp-system-migrations.sql');
const ADAPTER_PATH = path.join(ROOT, 'web/public/assets/erp-system-data-adapter.js');
const checkOnly = process.argv.includes('--check');

const journal = JSON.parse(readFileSync(JOURNAL_PATH, 'utf8'));
const entries = journal.entries;
if (!Array.isArray(entries) || entries.length === 0) {
  throw new Error('Drizzle migration journal is empty');
}

function migration(entry) {
  return readFileSync(path.join(DRIZZLE_DIR, `${entry.tag}.sql`), 'utf8').trim();
}

const fresh = [
  '-- GENERATED by scripts/generate-demo-schema.mjs from drizzle/meta/_journal.json.',
  '-- Do not edit by hand. Regenerate with: npm run generate:demo-schema',
  ...entries.map((entry) => `\n-- ${entry.tag}\n${migration(entry)}`),
  '',
].join('\n');

const LEGACY_PASSWORD_UPGRADE = `-- 0001_quiet_blizzard
-- Legacy demo users predate password auth. Backfill them with the public demo
-- password hash (demo1234) before restoring the current NOT NULL invariant.
ALTER TABLE "app_user" ADD COLUMN IF NOT EXISTS "password_hash" text;
UPDATE "app_user"
SET "password_hash" = 'pbkdf2$100000$e154d2b848d8c3d5d3d5f494b7fd446c$a299c39883dd29e1d800946af0be615e603f907ba0f4156ebdd2b287ccd4fc48'
WHERE "password_hash" IS NULL;
ALTER TABLE "app_user" ALTER COLUMN "password_hash" SET NOT NULL;`;

function compatibilitySql(entry) {
  const sql = migration(entry);
  if (/\bDROP\s+(TABLE|COLUMN)\b/i.test(sql)) {
    throw new Error(`${entry.tag} contains destructive DDL; write an explicit expand/backfill compatibility migration`);
  }
  const compatible = sql
    .replace(
      /CREATE TABLE "(?!IF NOT EXISTS )/g,
      'CREATE TABLE IF NOT EXISTS "',
    )
    .replace(
      /ALTER TABLE "([^"]+)" ADD COLUMN "(?!IF NOT EXISTS )/g,
      'ALTER TABLE "$1" ADD COLUMN IF NOT EXISTS "',
    )
    .replace(/DROP INDEX "(?!IF EXISTS )/g, 'DROP INDEX IF EXISTS "')
    .replace(/CREATE (UNIQUE )?INDEX "(?!IF NOT EXISTS )/g, 'CREATE $1INDEX IF NOT EXISTS "');

  return compatible
    .split('--> statement-breakpoint')
    .map((statement) => {
      const match = statement.match(
        /^\s*ALTER TABLE "([^"]+)" ADD CONSTRAINT "([^"]+)" ([\s\S]+);\s*$/,
      );
      if (!match) return statement;
      const [, table, constraint, definition] = match;
      return [
        'DO $$ BEGIN',
        ` ALTER TABLE "${table}" ADD CONSTRAINT "${constraint}" ${definition};`,
        'EXCEPTION WHEN duplicate_object THEN null;',
        'END $$;',
      ].join('\n');
    })
    .join('\n--> statement-breakpoint\n');
}

const compatibility = [
  '-- GENERATED by scripts/generate-demo-schema.mjs from Drizzle migrations.',
  '-- Idempotent upgrade bundle for persistent PGlite / IndexedDB databases.',
  LEGACY_PASSWORD_UPGRADE,
  ...entries.slice(2).map((entry) => `\n-- ${entry.tag}\n${compatibilitySql(entry)}`),
  '',
].join('\n');

const version = Math.max(...entries.map((entry) => Number(entry.idx)));
const adapter = readFileSync(ADAPTER_PATH, 'utf8');
const nextAdapter = adapter.replace(
  /var DEMO_SCHEMA_VERSION = \d+;/,
  `var DEMO_SCHEMA_VERSION = ${version};`,
);
if (nextAdapter === adapter && !adapter.includes(`var DEMO_SCHEMA_VERSION = ${version};`)) {
  throw new Error('Could not update DEMO_SCHEMA_VERSION in browser adapter');
}

const outputs = [
  [SCHEMA_PATH, fresh],
  [MIGRATIONS_PATH, compatibility],
  [ADAPTER_PATH, nextAdapter],
];

if (checkOnly) {
  const changed = outputs.filter(([file, content]) => readFileSync(file, 'utf8') !== content);
  if (changed.length) {
    console.error(`Generated PGlite artifacts are stale:\n${changed.map(([file]) => `- ${path.relative(ROOT, file)}`).join('\n')}`);
    process.exit(1);
  }
  console.log(`PGlite artifacts match ${entries.length} ordered Drizzle migrations (schema version ${version}).`);
} else {
  for (const [file, content] of outputs) writeFileSync(file, content);
  console.log(`Generated PGlite schema + compatibility bundle at version ${version}.`);
}
