// Compile the current migration chain's unique-index contract into the Demo runtime.
// This is schema metadata only: no seeds, grants or data backfills are executed.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const targets = new Map();
for (const file of readdirSync('web/public/db').filter(name => /^erp-system-(demo-.*|showcase-v1)\.sql$/.test(name))) {
  const sql = readFileSync('web/public/db/' + file, 'utf8');
  for (const insert of sql.matchAll(/INSERT INTO\s+"?(\w+)"?([\s\S]*?)(?=INSERT INTO|$)/gi)) {
    for (const conflict of insert[2].matchAll(/ON CONFLICT\s*\(([^)]+)\)/gi)) {
      const columns = conflict[1].split(',').map(value => value.replace(/["\s]/g, '')).sort();
      targets.set(insert[1] + ':' + columns.join(','), { table: insert[1], columns });
    }
  }
}
const client = new PGlite();
try {
  await client.exec(readFileSync('web/public/db/erp-system-schema.sql', 'utf8'));
  const { rows } = await client.query(`
    select index_class.relname as name, table_class.relname as table,
           pg_get_indexdef(index_class.oid) as definition,
           coalesce(constraint_row.contype::text, '') as constraint,
           array(select attribute.attname from unnest(index_row.indkey) with ordinality as key(attnum, ord)
             join pg_attribute attribute on attribute.attrelid=table_class.oid and attribute.attnum=key.attnum
             order by key.ord) as columns
    from pg_index index_row
    join pg_class index_class on index_class.oid=index_row.indexrelid
    join pg_class table_class on table_class.oid=index_row.indrelid
    join pg_namespace namespace on namespace.oid=table_class.relnamespace
    left join pg_constraint constraint_row on constraint_row.conindid=index_class.oid
      and constraint_row.conrelid=table_class.oid and constraint_row.contype in ('p','u')
    where namespace.nspname='public' and index_row.indisunique and index_row.indpred is null
    order by table_class.relname,index_class.relname`);
  const required = rows.filter(row => targets.has(row.table + ':' + [...row.columns].sort().join(',')));
  for (const [key] of targets) {
    if (!required.some(row => row.table + ':' + [...row.columns].sort().join(',') === key)) {
      throw new Error('No canonical startup ON CONFLICT arbiter: ' + key);
    }
  }
  const text = '// GENERATED by scripts/generate-demo-unique-indexes.mjs. Do not edit.\n' +
    '// Exact canonical startup unique indexes; retained Demo repair never rewrites records.\n' +
    'export const DEMO_UNIQUE_INDEXES = ' + JSON.stringify(required.map(row => ({ name: row.name, table: row.table, definition: row.definition, constraint: row.constraint })), null, 2) + ' as const;\n';
  const target = 'src/demo/uniqueIndexes.generated.ts';
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== text) throw new Error('Demo unique-index contract is stale. Run npm run generate:demo-indexes.');
    console.log(`Checked ${required.length} canonical unique indexes.`);
  } else {
    writeFileSync(target, text);
    console.log(`Generated ${required.length} canonical unique indexes.`);
  }
} finally { await client.close(); }
