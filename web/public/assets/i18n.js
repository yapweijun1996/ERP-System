let LANG = 'en';
try{ const s=localStorage.getItem('aria-lang'); if(s && I18N[s]) LANG=s; }catch(e){}

function getLang(){ return LANG; }
/* translate; falls back to English then to the key itself */
function t(key){
  const d=I18N[LANG]||I18N.en;
  return d[key]!=null ? d[key] : (I18N.en[key]!=null ? I18N.en[key] : key);
}
/* translate with an explicit fallback (for data-driven labels) */
function tf(key, fallback){
  const d=I18N[LANG]||I18N.en;
  return d[key]!=null ? d[key] : (I18N.en[key]!=null ? I18N.en[key] : fallback);
}
/* translate a data-driven status / enum value (e.g. "Pending Approval") */
function ts(value){
  return tf('st.'+value, value);
}

function setLang(code){
  if(!I18N[code] || code===LANG) return;
  LANG=code;
  try{ localStorage.setItem('aria-lang',code); }catch(e){}
  document.documentElement.setAttribute('lang', code==='zh'?'zh-Hans':code);
  applyI18n();
}

/* apply translations to the static markup carrying data-i18n* hooks */
function applyStaticI18n(){
  $$('[data-i18n]').forEach(el=>{ el.textContent=t(el.getAttribute('data-i18n')); });
  $$('[data-i18n-ph]').forEach(el=>{ el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
  $$('[data-i18n-tip]').forEach(el=>{ el.setAttribute('data-tip', t(el.getAttribute('data-i18n-tip'))); });
}

